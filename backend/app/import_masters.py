def _to_bool(value, default=True):
    if value is None or value == "":
        return default
    if isinstance(value, bool):
        return value
    return str(value).strip().lower() in {"true", "yes", "y", "1", "active"}


def _to_datetime(value):
    if value in (None, ""):
        return None
    if isinstance(value, datetime):
        return value
    text = str(value).strip()
    for parser in (
        datetime.fromisoformat,
        lambda x: datetime.strptime(x, "%d/%m/%Y"),
        lambda x: datetime.strptime(x, "%Y-%m-%d"),
    ):
        try:
            return parser(text)
        except (ValueError, TypeError):
            pass
    return None


def _clean_record(model_class, record):
    cleaned = dict(record)
    column_names = {c.name for c in model_class.__table__.columns}

    for key in list(cleaned.keys()):
        if key not in column_names:
            cleaned.pop(key, None)

    if "active" in cleaned:
        cleaned["active"] = _to_bool(cleaned.get("active"), True)
    if "force_password_reset" in cleaned:
        cleaned["force_password_reset"] = _to_bool(cleaned.get("force_password_reset"), False)

    for key in ("date_of_joining", "last_updated"):
        if key in cleaned:
            cleaned[key] = _to_datetime(cleaned.get(key))

    if "mobile" in cleaned and cleaned["mobile"] is not None:
        value = cleaned["mobile"]
        if isinstance(value, float) and value.is_integer():
            value = int(value)
        cleaned["mobile"] = str(value).strip()

    if "password" in cleaned and cleaned["password"] is not None:
        value = cleaned["password"]
        if isinstance(value, float) and value.is_integer():
            value = int(value)
        cleaned["password"] = str(value)

    return cleaned


def upsert_rows(db, model_class, rows):
    inserted = 0
    updated = 0

    for raw in rows:
        if not raw.get("id"):
            continue

        record = _clean_record(model_class, raw)
        existing = db.get(model_class, record["id"])

        if existing is None:
            db.add(model_class(**record))
            inserted += 1
        else:
            for key, value in record.items():
                if key != "id":
                    setattr(existing, key, value)
            updated += 1

    return inserted, updated


