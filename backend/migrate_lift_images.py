from sqlalchemy import inspect, text
from app.database import engine


def migrate():
    inspector = inspect(engine)

    with engine.begin() as conn:

        if not inspector.has_table("lift_images"):

            if engine.dialect.name == "postgresql":
                conn.execute(text("""
                    CREATE TABLE lift_images (
                        id VARCHAR(32) PRIMARY KEY,
                        name VARCHAR(255) NOT NULL,
                        category VARCHAR(30) NOT NULL,
                        image_data BYTEA NOT NULL,
                        content_type VARCHAR(50) NOT NULL,
                        created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
                    )
                """))
            else:
                conn.execute(text("""
                    CREATE TABLE lift_images (
                        id VARCHAR(32) PRIMARY KEY,
                        name VARCHAR(255) NOT NULL,
                        category VARCHAR(30) NOT NULL,
                        image_data BLOB NOT NULL,
                        content_type VARCHAR(50) NOT NULL,
                        created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
                    )
                """))

            print("CREATED: lift_images")
        else:
            print("EXISTS: lift_images")

        if not inspector.has_table("quotation_images"):

            if engine.dialect.name == "postgresql":
                conn.execute(text("""
                    CREATE TABLE quotation_images (
                        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        quotation_id INTEGER NOT NULL,
                        image_id VARCHAR(32) NOT NULL,
                        category VARCHAR(30) NOT NULL,
                        display_order INTEGER NOT NULL,
                        created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
                    )
                """))
            else:
                conn.execute(text("""
                    CREATE TABLE quotation_images (
                        id INTEGER PRIMARY KEY AUTOINCREMENT,
                        quotation_id INTEGER NOT NULL,
                        image_id VARCHAR(32) NOT NULL,
                        category VARCHAR(30) NOT NULL,
                        display_order INTEGER NOT NULL,
                        created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
                    )
                """))

            print("CREATED: quotation_images")
        else:
            print("EXISTS: quotation_images")

    print("IMAGE MIGRATION COMPLETED")


if __name__ == "__main__":
    migrate()
